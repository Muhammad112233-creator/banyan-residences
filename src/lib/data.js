// ---- Residences page inventory (sample) ----
const wings = ['A', 'B'];
const roomCycle = [1, 2, 2.5, 1.5, 3, 2, 1, 4];
export const residenceUnits = Array.from({ length: 36 }, (_, i) => {
  const floor = Math.floor(i / 6) + 1;
  const wing = wings[i % 2];
  const rooms = roomCycle[i % roomCycle.length];
  const area = Math.round((30 + rooms * 18 + (i % 5) * 3.4) * 100) / 100;
  return {
    id: `${wing} ${floor}.${String((i % 6) + 1).padStart(2, '0')}`,
    area,
    rooms,
    floor,
    wing,
    features: i % 3 === 0 ? 'Garden' : 'Balcony',
  };
});

export const retailUnits = Array.from({ length: 24 }, (_, i) => {
  const floor = Math.floor(i / 4) + 1;
  const wing = ['A', 'B', 'V'][i % 3];
  const area = Math.round((120 + (i % 7) * 42.5) * 100) / 100;
  return {
    id: `${wing}${floor}.PP${(i % 2) + 1}`,
    area,
    floor,
    wing,
    type: i % 4 === 0 ? 'Retail' : 'Offices',
  };
});

